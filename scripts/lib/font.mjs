export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;

export function measureText(text, scale = 1, tracking = 1) {
  const chars = [...text.toUpperCase()];
  if (chars.length === 0) return 0;
  return chars.length * (GLYPH_WIDTH + tracking) * scale - tracking * scale;
}

/** Draw `text` onto a Canvas with its top-left at (x, y). */
export function drawText(canvas, text, x, y, color, scale = 1, tracking = 1) {
  let cursor = x;
  for (const rawChar of text.toUpperCase()) {
    const glyph = GLYPHS[rawChar] ?? GLYPHS['?'];
    const rows = glyph.split(',');
    for (let ry = 0; ry < rows.length; ry++) {
      for (let rx = 0; rx < rows[ry].length; rx++) {
        if (rows[ry][rx] !== '1') continue;
        canvas.rect(cursor + rx * scale, y + ry * scale, scale, scale, color);
      }
    }
    cursor += (GLYPH_WIDTH + tracking) * scale;
  }
}

/** Draw text centred horizontally on `centerX`. */
export function drawTextCentered(canvas, text, centerX, y, color, scale = 1, tracking = 1) {
  drawText(
    canvas,
    text,
    centerX - measureText(text, scale, tracking) / 2,
    y,
    color,
    scale,
    tracking,
  );
}
